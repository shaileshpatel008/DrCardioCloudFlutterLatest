import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../../../data/models/ecg_record_model.dart';
import '../ecg/ecg_data.dart';
import '../storage_service.dart';
import 'pdf_report_shared.dart';

/// "Modern Clean" — this app's own from-scratch redesign of the report
/// layout (white background, light-bordered cells, brand-red accents),
/// replacing `SupportClass.PdfGenerator`'s manual `Canvas`/`Paint`
/// pixel-position drawing — the source of the "outdated, misaligned"
/// report the client originally flagged. Now one of 4 selectable formats
/// rather than the only one.
class ModernCleanReportBuilder {
  ModernCleanReportBuilder._();


  static void addPages(
    pw.Document doc,
    EcgRecordModel record,
    StorageService storage,
    List<String> reportTypes,
    pw.MemoryImage? photoImage,
    pw.MemoryImage? signatureImage,
  ) {
    doc.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4.landscape,
        margin: const pw.EdgeInsets.all(28),
        header: (context) => _buildLetterhead(storage, record),
        build: (context) => [
          for (var i = 0; i < reportTypes.length; i++) ...[
            if (i > 0) pw.NewPage(),
            ..._buildReportPage(record, storage, reportTypes[i], photoImage, signatureImage),
          ],
        ],
        footer: (context) => pw.Column(
          children: [
            pw.Divider(color: PdfReportShared.borderColor),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text('Generated by Dr. Cardio ECG', style: pw.TextStyle(fontSize: 7, color: PdfReportShared.mutedColor)),
                pw.Text('Page ${context.pageNumber} of ${context.pagesCount}', style: pw.TextStyle(fontSize: 7, color: PdfReportShared.mutedColor)),
              ],
            ),
          ],
        ),
      ),
    );
  }

  static List<pw.Widget> _buildReportPage(
    EcgRecordModel record,
    StorageService storage,
    String reportType,
    pw.MemoryImage? photoImage,
    pw.MemoryImage? signatureImage,
  ) {
    final simultaneous = reportType.startsWith('Simultaneous');
    final (columns, rowsPerColumn) = PdfReportShared.gridShape(reportType);

    final analysisStrip = _buildAnalysisStrip(record);
    final notesBlock = _buildNotesBlock(record);

    return [
      pw.SizedBox(height: 10),
      _buildPatientInfoTable(record, photoImage),
      if (notesBlock != null) ...[
        pw.SizedBox(height: 8),
        notesBlock,
      ],
      if (analysisStrip != null) ...[
        pw.SizedBox(height: 8),
        analysisStrip,
      ],
      pw.SizedBox(height: 14),
      pw.Text('12-LEAD ECG - ${reportType.toUpperCase()}', style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold, color: PdfReportShared.brandColor)),
      pw.SizedBox(height: 6),
      _buildLeadGrid(record, columns: columns, rowsPerColumn: rowsPerColumn, simultaneous: simultaneous),
      if (reportType.contains('4x3')) ...[
        pw.SizedBox(height: 14),
        pw.Text('RHYTHM STRIP - LEAD ${storage.longLead}', style: pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold, color: PdfReportShared.brandColor)),
        pw.SizedBox(height: 6),
        _buildRhythmStrip(record, storage.longLead),
      ],
      if (signatureImage != null) ...[
        pw.SizedBox(height: 14),
        _buildSignatureBlock(signatureImage),
      ],
      pw.SizedBox(height: 16),
      _buildCalibrationFooter(record, storage),
    ];
  }

  static pw.Widget _buildLetterhead(StorageService storage, EcgRecordModel record) {
    final doctorLine = [storage.doctorName, storage.doctorContactNo, storage.doctorAddress].where((s) => s.isNotEmpty).join('   |   ');
    return pw.Column(
      children: [
        pw.Row(
          crossAxisAlignment: pw.CrossAxisAlignment.center,
          children: [
            pw.Container(width: 34, height: 34, decoration: pw.BoxDecoration(color: PdfReportShared.brandColor, shape: pw.BoxShape.circle)),
            pw.SizedBox(width: 10),
            pw.Expanded(
              child: pw.Column(
                crossAxisAlignment: pw.CrossAxisAlignment.start,
                children: [
                  pw.Text('Dr. Cardio', style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold, color: PdfReportShared.brandColor)),
                  pw.Text(
                    storage.clinicName.isEmpty ? 'ECG in your pocket' : storage.clinicName,
                    style: pw.TextStyle(fontSize: 8.5, color: PdfReportShared.mutedColor),
                  ),
                ],
              ),
            ),
            pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.end,
              children: [
                pw.Text('12-Lead ECG Report', style: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold, color: PdfReportShared.inkColor)),
                pw.Text('Acquired: ${PdfReportShared.formatDate(record.dateTime)}', style: pw.TextStyle(fontSize: 8, color: PdfReportShared.mutedColor)),
              ],
            ),
          ],
        ),
        if (doctorLine.isNotEmpty) ...[
          pw.SizedBox(height: 4),
          pw.Text(doctorLine, style: pw.TextStyle(fontSize: 8.5, fontWeight: pw.FontWeight.bold, color: PdfReportShared.inkColor)),
        ],
        pw.SizedBox(height: 8),
        pw.Container(height: 2, color: PdfReportShared.brandColor),
      ],
    );
  }

  static pw.Widget _infoField(String label, String value) => pw.Expanded(
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text(label, style: pw.TextStyle(fontSize: 7, color: PdfReportShared.mutedColor)),
            pw.SizedBox(height: 2),
            pw.Text(value.isEmpty ? '-' : value, style: pw.TextStyle(fontSize: 9.5, fontWeight: pw.FontWeight.bold, color: PdfReportShared.inkColor)),
          ],
        ),
      );

  static pw.Widget _buildPatientInfoTable(EcgRecordModel record, pw.MemoryImage? photoImage) {
    return pw.Container(
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfReportShared.borderColor), borderRadius: pw.BorderRadius.circular(6)),
      child: pw.Row(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Expanded(
            child: pw.Column(
              children: [
                pw.Row(children: [
                  _infoField('PATIENT', record.patient.name),
                  _infoField('ID', record.patient.patientId),
                  _infoField('AGE / SEX', '${record.patient.age.isEmpty ? '-' : record.patient.age} / ${record.patient.sex}'),
                ]),
                pw.SizedBox(height: 8),
                pw.Row(children: [_infoField('DEVICE', record.deviceName)]),
              ],
            ),
          ),
          if (photoImage != null) ...[
            pw.SizedBox(width: 10),
            pw.Container(
              width: 42,
              height: 42,
              decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfReportShared.borderColor, width: 0.6), borderRadius: pw.BorderRadius.circular(4)),
              child: pw.ClipRRect(horizontalRadius: 4, verticalRadius: 4, child: pw.Image(photoImage, fit: pw.BoxFit.cover)),
            ),
          ],
        ],
      ),
    );
  }

  static pw.Widget? _buildAnalysisStrip(EcgRecordModel record) {
    final items = PdfReportShared.analysisItems(record);
    if (items.isEmpty) return null;
    return pw.Container(
      padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 8),
      decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfReportShared.borderColor), borderRadius: pw.BorderRadius.circular(6)),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: items
            .map((e) => pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(e.key, style: pw.TextStyle(fontSize: 6.5, fontWeight: pw.FontWeight.bold, color: PdfReportShared.mutedColor)),
                    pw.SizedBox(height: 2),
                    pw.Text(e.value, style: pw.TextStyle(fontSize: 9, fontWeight: pw.FontWeight.bold, color: PdfReportShared.inkColor)),
                  ],
                ))
            .toList(),
      ),
    );
  }

  static pw.Widget? _buildNotesBlock(EcgRecordModel record) {
    final medications = record.patient.medications.trim();
    final comments = record.patient.comments.trim();
    if (medications.isEmpty && comments.isEmpty) return null;
    return pw.Container(
      width: double.infinity,
      padding: const pw.EdgeInsets.symmetric(horizontal: 10, vertical: 8),
      decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfReportShared.borderColor), borderRadius: pw.BorderRadius.circular(6)),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          if (medications.isNotEmpty) ...[
            pw.Text('MEDICATIONS', style: pw.TextStyle(fontSize: 6.5, fontWeight: pw.FontWeight.bold, color: PdfReportShared.mutedColor)),
            pw.SizedBox(height: 2),
            pw.Text(medications, style: pw.TextStyle(fontSize: 8.5, color: PdfReportShared.inkColor)),
          ],
          if (medications.isNotEmpty && comments.isNotEmpty) pw.SizedBox(height: 6),
          if (comments.isNotEmpty) ...[
            pw.Text('COMMENTS', style: pw.TextStyle(fontSize: 6.5, fontWeight: pw.FontWeight.bold, color: PdfReportShared.mutedColor)),
            pw.SizedBox(height: 2),
            pw.Text(comments, style: pw.TextStyle(fontSize: 8.5, color: PdfReportShared.inkColor)),
          ],
        ],
      ),
    );
  }

  static pw.Widget _buildSignatureBlock(pw.MemoryImage signatureImage) {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.end,
      children: [
        pw.Column(
          children: [
            pw.Container(
              width: 100,
              height: 30,
              alignment: pw.Alignment.bottomCenter,
              padding: const pw.EdgeInsets.only(bottom: 2),
              decoration: pw.BoxDecoration(border: pw.Border(bottom: pw.BorderSide(color: PdfReportShared.borderColor, width: 0.8))),
              child: pw.Image(signatureImage, fit: pw.BoxFit.contain, height: 26),
            ),
            pw.SizedBox(height: 3),
            pw.Text('PATIENT SIGNATURE', style: pw.TextStyle(fontSize: 6, fontWeight: pw.FontWeight.bold, color: PdfReportShared.mutedColor)),
          ],
        ),
      ],
    );
  }

  static pw.Widget _buildLeadGrid(EcgRecordModel record, {required int columns, required int rowsPerColumn, required bool simultaneous}) {
    final cellHeight = rowsPerColumn > 6 ? 34.0 : (rowsPerColumn > 4 ? 40.0 : 46.0);
    final columnWidgets = <pw.Widget>[];
    for (var col = 0; col < columns; col++) {
      final cells = <pw.Widget>[];
      for (var row = 0; row < rowsPerColumn; row++) {
        final index = PdfReportShared.leadIndexForCell(col, row, rowsPerColumn);
        final leadName = PdfReportShared.leadNameAt(index);
        final full = PdfReportShared.leadSamplesAt(record, index);
        final samples = simultaneous ? full : PdfReportShared.sequentialSlice(full, columns, col);
        cells.add(pw.Container(
          margin: const pw.EdgeInsets.all(2),
          height: cellHeight,
          decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfReportShared.borderColor, width: 0.5)),
          child: pw.Stack(children: [
            pw.Positioned(top: 2, left: 3, child: pw.Text(leadName, style: pw.TextStyle(fontSize: 6, color: PdfReportShared.mutedColor))),
            pw.Center(child: PdfReportShared.tracePainter(samples, width: columns == 1 ? 700 : 720 / columns, height: cellHeight - 6)),
          ]),
        ));
      }
      columnWidgets.add(pw.Expanded(child: pw.Column(children: cells)));
    }
    return pw.Row(crossAxisAlignment: pw.CrossAxisAlignment.start, children: columnWidgets);
  }

  static pw.Widget _buildRhythmStrip(EcgRecordModel record, String longLead) {
    final samples = PdfReportShared.leadSamplesAt(record, _longLeadIndex(longLead));
    return pw.Container(
      height: 60,
      decoration: pw.BoxDecoration(border: pw.Border.all(color: PdfReportShared.borderColor, width: 0.5)),
      child: pw.Center(child: PdfReportShared.tracePainter(samples, width: 520, height: 54)),
    );
  }

  static int _longLeadIndex(String longLead) {
    final index = EcgData.leadName.indexOf(longLead);
    return index == -1 ? 1 : index;
  }

  static pw.Widget _buildCalibrationFooter(EcgRecordModel record, StorageService storage) {
    return pw.Row(
      crossAxisAlignment: pw.CrossAxisAlignment.center,
      children: [
        pw.Expanded(
          child: pw.Text(
            '${storage.xAxisScale} mm/s | 10 mm/mV | ${record.filter}',
            style: pw.TextStyle(fontSize: 8, color: PdfReportShared.mutedColor),
          ),
        ),
        pw.Expanded(
          child: pw.Column(
            children: [
              pw.Text('To be Finally Confirmed by the doctor', textAlign: pw.TextAlign.center, style: pw.TextStyle(fontSize: 7.5, fontWeight: pw.FontWeight.bold, color: PdfReportShared.inkColor)),
              pw.Text('Software calculated values. To be verified manually', textAlign: pw.TextAlign.center, style: pw.TextStyle(fontSize: 7, color: PdfReportShared.mutedColor)),
            ],
          ),
        ),
        pw.Expanded(
          child: pw.Text('Gain: ${record.gain}', textAlign: pw.TextAlign.right, style: pw.TextStyle(fontSize: 8, color: PdfReportShared.mutedColor)),
        ),
      ],
    );
  }
}
